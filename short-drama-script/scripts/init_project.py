def episode_tpl(title: str, english: str) -> str:
    return f"""{title} · {english} · 第 1 集：<集名>
(人物名称英文 · 台词英文；场景、动作与语气提示为中文)

本集概要：<3–6 句中文；不出现“他／她”，一律用人名>
【本集大场面】
· <场号范围> <大场面名>：必须看到什么（规模与比例参照、物理后果；不写运镜）
本集人物：<主角 → 群像 → 反派；这一集出现过的全部人物>
本集场景：<这一集用到的全部场景，写到子视图>


【1-1 日 外 <母场景·子视图>】
人物：<资产命名表里的人物名、顿号分隔>

△（远景）<看得见的东西：地点、时间、体量、天气。>
△（近景）<这一场的第一个动作：谁做什么，动作要有结束状态。>

<角色名>（<语气或策略提示>）：<台词原句>
"""


def write(path: Path, text: str, created: list, skipped: list):
    if path.exists():
        skipped.append(path.name)
        return
    path.write_text(text, encoding="utf-8")
    created.append(path.name)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("project", type=Path)
    ap.add_argument("--title", required=True)
    ap.add_argument("--english-name", default="TITLE")
    ap.add_argument("--episodes", type=int, default=12)
    args = ap.parse_args()

    root: Path = args.project
    root.mkdir(parents=True, exist_ok=True)
    for d in ("交付", "审查"):
        (root / d).mkdir(exist_ok=True)

    created, skipped = [], []
    write(root / f"{args.title}-全局设定.txt", settings_tpl(args.title), created, skipped)
    write(root / f"{args.title}-第一季整体大纲.txt",
          outline_tpl(args.title, args.episodes), created, skipped)
    write(root / f"{args.title}-台词对照本.txt",
          f"""{args.title} · 台词对照本（全 {args.episodes} 集）
英文为正文原句，中文为大意，仅用于审稿；人名一律用英文。
场标与集内编号与《第 N 集.txt》一致。

（本文件由 scripts/build_derived_docs.py 生成与对账，不要手工维护。）
""", created, skipped)
    write(root / f"{args.title}-分集场次表.txt",
          f"""{args.title} · 分集场次表
（本文件由 scripts/build_derived_docs.py 从正本生成，不要手工维护。）
""", created, skipped)
    write(root / "第1集.txt", episode_tpl(args.title, args.english_name), created, skipped)

    print(f"项目：{root}")
    if created:
        print("已创建：")
        for n in created:
            print("   ", n)
    if skipped:
        print("已存在，跳过（未覆盖）：")
        for n in skipped:
            print("   ", n)
    print(f"""
下一步：
1. 把《{args.title}-全局设定.txt》的资产命名表填起来（场景 S / 人物 CH / 物品 PR）
2. 用《{args.title}-第一季整体大纲.txt》写逐日锚点与分集地图
3. 按 $short-drama-script 的 references/format-spec.md 写第 1 集
4. 写完跑：python3 scripts/build_derived_docs.py {root}
5. 交审查：$short-drama-script-audit 的 scripts/audit_plain_script.py {root}
""")
    return 0


if __name__ == "__main__":
    sys.exit(main())
